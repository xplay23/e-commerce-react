// Неизвестный или отсутствующий язык всегда заменяется базовым украинским.
export function normalizeLanguage(language) {
  return languages.includes(language) ? language : 'uk'
}
export function readLanguage(storage) {
  try {
    return normalizeLanguage(storage.getItem('nord-language'))
  } catch {
    return 'uk'
  }
}
export function translate(key, language = 'uk', values = {}) {
  const lang = normalizeLanguage(language)
  // PHP возвращает сообщения на английском; динамические ошибки разбираем отдельно,
  // чтобы сохранить статус или имя обязательного поля в переводе.
  const serverError = /^Ошибка сервера \((\d+)\)$/.exec(key)
  if (serverError) return translate('Ошибка сервера ({status})', lang, { status: serverError[1] })
  const fieldError = /^Field '([^']+)' is required$/.exec(key)
  if (fieldError) return translate('Обязательное поле: {field}', lang, { field: fieldError[1] })
  const text =
    lang === 'ru' ? russianErrors[key] || key : messages[key]?.[lang === 'uk' ? 0 : 1] || key
  return text.replace(/\{(\w+)\}/g, (match, name) =>
    values[name] === undefined ? match : String(values[name]),
  )
}
